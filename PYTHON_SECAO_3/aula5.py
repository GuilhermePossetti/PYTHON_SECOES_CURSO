# Tipo de dado bool (boolean)
# Ao questionar algo em um programa,
# só existem duas respostas posseíveis:
#sim (True) ou não (False).
# Existem vário operadores para "questionar".
# Dentre eles o ==, que é igual a outro
print(10==10) # Sim=> (verdadeiro)
print(10 == 11) # Não => (falso)
print(type(10 == 10))
print(type(10 == 11))